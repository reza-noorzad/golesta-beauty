  await page.setViewportSize({width:430,height:800});
  const fixture=await adminFixture(page,baseURL!);
  const before=structuredClone(fixture.content());
  await signIn(page,"/admin/einstellungen");
  await page.getByRole("textbox",{name:"Salonname",exact:true}).fill("Salonname im isolierten Test");
